import assert from 'node:assert/strict';
import {createSyncMaster} from './sync-master.js';
import {synchronizeSimple} from './sync.js';
import {createSmartSync} from './smart-sync.js';
const a={index:0,track:{bpm:124},playing:false,rate:1.04};
const b={index:1,track:{bpm:115},playing:false,rate:1};
const policy=createSyncMaster({decks:()=>[a,b]});
a.playing=true;policy.started(a);
assert.equal(policy.plan(b).leader,a,'incoming paused deck must follow the playing deck');
b.playing=true;policy.started(b);
for(const clicked of [a,b])assert.deepEqual(policy.plan(clicked),{leader:a,follower:b},'either Sync button preserves the outgoing master');
a.playing=false;
assert.equal(policy.master(),b,'a stopped auto master yields to the playing deck');
a.playing=true;policy.started(a);
assert.equal(policy.plan(a).leader,b,'reversed playback order selects the outgoing right deck');
policy.select(a);
assert.equal(policy.plan(b).leader,a,'explicit MASTER choice overrides auto order');
a.track={bpm:130};
assert.equal(policy.master(),b,'loading a replacement cannot inherit explicit master ownership');
policy.select(null);
assert.equal(a.rate,1.04,'choosing leadership must not retime the outgoing deck');
assert.equal(b.rate,1);
console.log('Sync master: incoming/paused, either-button, reverse order, stop, explicit choice and load ownership pass.');
const outgoing={index:0,track:{bpm:124,grid:0,duration:60},position:0,rate:1.04,playing:true};
const incoming={index:1,track:{bpm:115,grid:0,duration:60},position:0,rate:1,playing:false};
const changes=[];
const engine={position:d=>d.position,audibleRate:d=>d.rate,setRate:async(d,rate)=>{changes.push(d.index);d.rate=rate;}};
await synchronizeSimple({engine,deck:incoming,leader:outgoing});
assert.deepEqual(changes,[1]);assert.equal(outgoing.rate,1.04);
assert.equal(incoming.rate,124*1.04/115);
incoming.rate=1;changes.length=0;
const smart=createSmartSync({engine,state:{settings:{'Sync Mode':'Smart Sync'},decks:[outgoing,incoming]}});
assert.equal(smart.setMaster(outgoing),true);
await smart.press(incoming);
assert.deepEqual(changes,[1]);assert.equal(outgoing.rate,1.04);
assert.equal(incoming.rate,124*1.04/115);
assert.equal(outgoing.syncRole,'primary');assert.equal(incoming.syncRole,'secondary');
const external=createSmartSync({engine,state:{settings:{'Sync Mode':'Smart Sync'},decks:[outgoing,incoming]},externalLeader:()=>({valid:()=>true})});
assert.equal(external.setMaster(outgoing),false,'external clock retains its own leadership');
console.log('Real Simple/Smart Sync tempo paths change only the incoming deck; external clock ownership retained (controlled engine).');
