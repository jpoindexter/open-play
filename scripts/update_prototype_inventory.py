"""Generate read-only prototype evidence data and route accounting from canonical research."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
features = json.loads((ROOT / 'docs/delivery/feature-registry.json').read_text())['features']
requirements = json.loads((ROOT / 'docs/research/interaction-requirements.json').read_text())['requirements']
fx = json.loads((ROOT / 'docs/research/fx-catalog.json').read_text())
def route(f):
    key = f['id']
    if key.startswith('LIB'):
        return 'history' if key in ['LIB-008','LIB-016','LIB-017'] else 'library'
    if key.startswith('ANA'): return 'analysis'
    if key.startswith('DEK'): return 'decks'
    if key.startswith('MIX'): return 'mixer'
    if key.startswith('FX'): return 'fx'
    if key.startswith('SMP'): return 'sampler'
    if key.startswith('STM'): return 'stems'
    if key.startswith('REC'): return 'recording'
    if key.startswith('AUD'): return 'audio'
    if key.startswith('HW'): return 'midi' if key in ['HW-002','HW-003','HW-004','HW-012'] else 'hardware'
    if key.startswith('VID'): return 'video'
    if key.startswith('SCR'): return 'scratch'
    if key.startswith('FLP'): return 'flip'
    if key.startswith('LNK'): return 'link'
    if key.startswith('UI'): return 'help' if key=='UI-009' else 'settings'
    if key in ['SYS-003','SYS-009']: return 'providers'
    return 'system'

rows=[]
for f in features:
    rows.append(dict(**f, route=route(f), requirement_ids=[r['id'] for r in requirements if r['feature_id']==f['id']],
        prototype_status='Review surface assigned; per-requirement implementation and executed acceptance remain separately reported',
        native_status='BLOCKED — prototype approval required'))
out=ROOT/'prototype/inventory.js'
out.write_text('// Generated by scripts/update_prototype_inventory.py; no proprietary assets.\nexport const features = '+json.dumps(rows,ensure_ascii=False)+';\nexport const requirements = '+json.dumps(requirements,ensure_ascii=False)+';\nexport const fxCatalog = '+json.dumps(fx,ensure_ascii=False)+';\n')
manifest={'reference':'Serato DJ Pro 4.0.10.213','date':'2026-10-16','full_parity_verified':False,'features':[{k:r[k] for k in ['id','title','route','requirement_ids','prototype_status','native_status']} for r in rows]}
(ROOT/'docs/prototype/coverage-manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
head=['# Interaction requirements','','Full-scope working inventory. Evidence and runtime acceptance are separate. See the prototype report for what actually executes.','','| ID / feature | Screen | Trigger | Expected result | Evidence |','|---|---|---|---|---|']
for r in requirements:head.append(f"| {r['id']} / {r['feature_id']} | {r['screen']} | {r['trigger']} | {r['expected']} | [{r['evidence']}]({r['source_url']}) |")
(ROOT/'docs/research/INTERACTION_REQUIREMENTS.md').write_text('\n'.join(head)+'\n')
print(f'{len(rows)} feature routes, {len(requirements)} requirements, {fx["count"]} effects')

coverage=['# Feature coverage accountability','','Every feature remains in scope. A review route is not native acceptance. See [prototype review](../prototype/REVIEW_REPORT.md).','','| ID | Feature | Requirements | Native acceptance | Codex | Claude Code |','|---|---|---|---|---|---|']
for f in rows:
    reqs=' '.join(f['requirement_ids']) or 'Detailed extraction pending'
    coverage.append(f"| {f['id']} | {f['title']} | {len(f['requirement_ids'])}; {reqs} | {f['acceptance']} | {f['routing']['codex']['model']} / {f['routing']['codex']['effort']} | {f['routing']['claude_code']['model']} / {f['routing']['claude_code']['effort']} |")
(ROOT/'docs/research/FEATURE_COVERAGE.md').write_text('\n'.join(coverage)+'\n')
crosspath=ROOT/'docs/research/manual-feature-crosswalk.json'
cross=json.loads(crosspath.read_text())
for row in cross['rows']:
    row['requirement_ids']=[r['id'] for r in requirements if r.get('source_article')==row['article_id']]
crosspath.write_text(json.dumps(cross,indent=2)+'\n')
