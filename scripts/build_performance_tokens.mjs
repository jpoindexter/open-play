import {readFile,writeFile} from 'node:fs/promises';

// Dependency-free export for this plain-CSS app; DTCG source remains authoritative.
const source=JSON.parse(await readFile(new URL('../prototype/design-tokens/serato-core.tokens.json',import.meta.url),'utf8'));
const tokens=new Map();
function collect(group,path=[]){
  for(const [key,value] of Object.entries(group)){
    if(key.startsWith('$'))continue;
    const next=[...path,key];
    if(value&&typeof value==='object'&&'$value'in value)tokens.set(next.join('.'),value);
    else if(value&&typeof value==='object')collect(value,next);
  }
}
collect(source);
const cssName=path=>'--dj-'+path.replaceAll('.', '-').replace(/[A-Z]/g,c=>'-'+c.toLowerCase());
function validate(path,ancestors=new Set()){
  if(ancestors.has(path))throw Error('Token alias cycle: '+path);
  const token=tokens.get(path);if(!token)throw Error('Missing token alias: '+path);
  const alias=typeof token.$value==='string'&&token.$value.match(/^\{(.+)\}$/);
  if(alias)validate(alias[1],new Set([...ancestors,path]));
}
function cssValue(token){
  const v=token.$value;
  if(typeof v==='string')return v.replace(/\{([^}]+)\}/g,(_,path)=>`var(${cssName(path)})`);
  if(token.$type==='dimension')return String(v.value)+v.unit;
  if(token.$type==='fontFamily')return v.map(x=>['sans-serif','monospace','system-ui','ui-monospace'].includes(x)?x:JSON.stringify(x)).join(', ');
  return String(v);
}
const lines=[];
for(const [path,token] of tokens){validate(path);lines.push(`  ${cssName(path)}: ${cssValue(token)};`);}
await writeFile(new URL('../prototype/performance-tokens.css',import.meta.url),'/* Generated by scripts/build_performance_tokens.mjs; edit design-tokens/serato-core.tokens.json. */\n:root {\n'+lines.join('\n')+'\n}\n'+modeCSS());
function resolve(path){
  const value=tokens.get(path).$value,alias=typeof value==='string'&&value.match(/^\{(.+)\}$/);
  return alias?resolve(alias[1]):value;
}
const colors=Object.fromEntries([...tokens].filter(([path,token])=>path.startsWith('semantic.')&&token.$type==='color').map(([path])=>[path.slice(9),resolve(path)]));
await writeFile(new URL('../prototype/performance-tokens.js',import.meta.url),'// Generated from design-tokens/serato-core.tokens.json.\nexport const performanceColors = Object.freeze('+JSON.stringify(colors,null,2)+');\n');
const family=cssValue({$type:'fontFamily',$value:resolve('semantic.font')});
const typography=Object.fromEntries(['captionSize','microSize'].map(role=>[role,cssValue({$type:'dimension',$value:resolve('semantic.'+role)})+' '+family]));
await writeFile(new URL('../prototype/performance-tokens.js',import.meta.url),'export const performanceTypography=Object.freeze('+JSON.stringify(typography)+');\n',{flag:'a'});
console.log(`Exported ${tokens.size} core-performance tokens; aliases and cycles checked.`);

function modeCSS(){
 const mode=source.$extensions?.['org.openplay']?.dayMode||{};
 return 'body.day {\n'+Object.entries(mode).map(([role,value])=>{validate('semantic.'+role);validate(value.slice(1,-1));return '  '+cssName('semantic.'+role)+': '+cssValue({$value:value})+';';}).join('\n')+'\n}\n';
}
